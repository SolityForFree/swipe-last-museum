#!/usr/bin/env python3
"""Build the daily pool: a folder of images the daily 10 are drawn from,
with a fixed share of modern works (from 1900 on) vs older ones.

  pool/<id>.jpg     hard links to images/<id>.jpg (no extra disk space; copies if links fail)
  pool/pool.json    [{"id", "year", "modern"}]  read by api.php and swipe.html

Usage:
  python3 build_pool.py                          # rebuild pool from images already downloaded
  python3 build_pool.py --fetch-cma-modern 550   # first fetch more Cleveland works from 1900+ (CC0)
  python3 build_pool.py --size 1000 --modern-share 0.7

Rerun any time (e.g. after more Commons images finish downloading); the pool is rebuilt in place.
"""
import argparse
import json
import os
import random
import shutil
import time
import urllib.parse
from collections import defaultdict

DATA_FILES = [("artworks.js", "ARTWORKS"), ("artworks_cma.js", "ARTWORKS_CMA"), ("artworks_commons.js", "ARTWORKS_COMMONS")]
MODERN_FROM = 1900


def load(path):
    if not os.path.exists(path):
        return []
    text = open(path, encoding="utf-8").read()
    return json.loads(text[text.index("["):text.rindex("]") + 1])


def save_cma(works, path="artworks_cma.js"):
    with open(path, "w", encoding="utf-8") as f:
        f.write("// Generated by build_cleveland.py / build_pool.py from the Cleveland Museum of Art Open Access API (CC0).\n")
        f.write("window.ARTWORKS_CMA = ")
        json.dump(works, f, ensure_ascii=False, separators=(",", ":"))
        f.write(";\n")


def fetch_cma_modern(n, images_dir):
    """Add about n more Cleveland CC0 paintings/prints/drawings created 1900 or later."""
    import build_cleveland as bc
    existing = load("artworks_cma.js")
    have = {a["id"] for a in existing}
    per_type = {"Painting": 0.35, "Print": 0.4, "Drawing": 0.25}
    raw = {}
    for t, share in per_type.items():
        want = int(n * share * 1.4)  # some will be duplicates
        base = {"cc0": 1, "has_image": 1, "type": t, "created_after": MODERN_FROM, "created_before": 2100}
        total = bc.get_json(bc.API + "?" + urllib.parse.urlencode({**base, "limit": 1, "fields": "id"}))["info"]["total"]
        print(f"Cleveland {t} from {MODERN_FROM}: {total} available", flush=True)
        # several random windows so we don't only get the first page
        for _ in range(4):
            limit = min(100, max(1, want // 4))
            skip = random.randint(0, max(0, total - limit))
            data = bc.get_json(bc.API + "?" + urllib.parse.urlencode({**base, "limit": limit, "skip": skip, "fields": bc.FIELDS}))
            for r in data["data"]:
                if ((r.get("images") or {}).get("web") or {}).get("url") and f"cma-{r['id']}" not in have:
                    raw[r["id"]] = r
            time.sleep(0.5)
    qids = [u.rsplit("/", 1)[1] for r in raw.values() for u in (r.get("external_resources") or {}).get("wikidata", [])]
    movements = bc.wikidata_movements(qids) if qids else {}
    new = [bc.to_record(r, movements) for r in raw.values()]
    for rec in new:
        rec.pop("_dept", None)
    random.shuffle(new)
    new = new[:n]
    print(f"Adding {len(new)} new Cleveland works from {MODERN_FROM}+; downloading images…", flush=True)
    failed = set(bc.download_images(new, images_dir))
    new = [w for w in new if w["id"] not in failed]
    save_cma(existing + new)
    print(f"artworks_cma.js now has {len(existing) + len(new)} works", flush=True)


def pick_balanced(works, k, key):
    """Round-robin across groups so no single style/century dominates."""
    groups = defaultdict(list)
    for w in works:
        groups[key(w)].append(w)
    for g in groups.values():
        random.shuffle(g)
    order = list(groups)
    random.shuffle(order)
    out = []
    while len(out) < k and any(groups.values()):
        for g in order:
            if groups[g] and len(out) < k:
                out.append(groups[g].pop())
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--size", type=int, default=1000)
    ap.add_argument("--modern-share", type=float, default=0.7)
    ap.add_argument("--fetch-cma-modern", type=int, default=0)
    ap.add_argument("--images", default="images")
    ap.add_argument("--pool", default="pool")
    ap.add_argument("--seed", type=int, default=3)
    args = ap.parse_args()
    random.seed(args.seed)

    if args.fetch_cma_modern:
        fetch_cma_modern(args.fetch_cma_modern, args.images)

    works = []
    for f, _ in DATA_FILES:
        works += [{**a, "id": str(a["id"])} for a in load(f)]
    usable = [w for w in works if os.path.exists(os.path.join(args.images, f"{w['id']}.jpg"))]
    modern = [w for w in usable if (w.get("year") or -10**9) >= MODERN_FROM]
    older = [w for w in usable if (w.get("year") or -10**9) < MODERN_FROM]

    want_modern = round(args.size * args.modern_share)
    want_older = args.size - want_modern
    if len(modern) < want_modern:
        # keep the ratio: shrink the pool rather than fill with older works
        want_modern = len(modern)
        want_older = min(len(older), round(want_modern * (1 - args.modern_share) / args.modern_share))
        print(f"Only {len(modern)} modern works have images; pool shrunk to keep the {args.modern_share:.0%} share.")

    era_style = lambda w: (w.get("era"), w.get("style"))
    chosen = pick_balanced(modern, want_modern, lambda w: (w.get("source"), w.get("type"), w.get("style"))) \
        + pick_balanced(older, want_older, era_style)

    os.makedirs(args.pool, exist_ok=True)
    keep = {f"{w['id']}.jpg" for w in chosen}
    for name in os.listdir(args.pool):
        if name.endswith(".jpg") and name not in keep:
            os.remove(os.path.join(args.pool, name))
    for w in chosen:
        src = os.path.join(args.images, f"{w['id']}.jpg")
        dst = os.path.join(args.pool, f"{w['id']}.jpg")
        if os.path.exists(dst):
            continue
        try:
            os.link(src, dst)
        except OSError:
            shutil.copy2(src, dst)

    entries = [{"id": w["id"], "year": w.get("year"), "modern": (w.get("year") or -10**9) >= MODERN_FROM} for w in chosen]
    payload = {"modern_from": MODERN_FROM, "modern_share": args.modern_share, "works": entries}
    with open(os.path.join(args.pool, "pool.json"), "w", encoding="utf-8") as f:
        json.dump(payload, f, separators=(",", ":"))
    with open(os.path.join(args.pool, "pool.js"), "w", encoding="utf-8") as f:  # for opening swipe.html as a file
        f.write("window.POOL = " + json.dumps(payload, separators=(",", ":")) + ";\n")

    m = sum(e["modern"] for e in entries)
    by_src = defaultdict(lambda: [0, 0])
    for w in chosen:
        by_src[w.get("source", "aic")][0 if (w.get("year") or -10**9) >= MODERN_FROM else 1] += 1
    print(f"\nPool: {len(entries)} works in {args.pool}/ — {m} from {MODERN_FROM}+ ({m / max(1, len(entries)):.0%}), "
          f"{len(entries) - m} older")
    for s, (a, b) in by_src.items():
        print(f"  {s:8s} {a:4d} modern  {b:4d} older")
    print(f"Available but unused: {len(modern) - m} modern, {len(older) - (len(entries) - m)} older")


if __name__ == "__main__":
    main()
